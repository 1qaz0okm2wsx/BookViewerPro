function essayToHtml(e: Essay): string {
  return (
    `<p style="text-align:center;color:#8a948c;font-size:.9em">${e.date}</p>\n` +
    e.paragraphs.map((p) => `<p>${p}</p>`).join("\n")
  );
}

/** 构建《毛泽东选集 · 老三篇》EPUB 与元数据 */
export async function buildMaoSample(): Promise<{ meta: BookMeta; blob: Blob }> {
  const title = "毛泽东选集 · 老三篇";
  const author = "毛泽东";
  const cover = await makeCover(title, author, "EPUB");
  const blob = await buildEpub({
    title,
    author,
    chapters: MAO_ESSAYS.map((e) => ({ title: e.title, html: essayToHtml(e) })),
    version: 3,
    cover,
  });
  const meta: BookMeta = {
    id: uid(),
    title,
    author,
    format: "epub",
    size: blob.size,
    addedAt: Date.now(),
    cover,
    source: "sample",
    tags: ["示例", "政治", "公有领域"],
  };
  return { meta, blob };
}
